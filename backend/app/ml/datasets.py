# Canonical label mapping, used everywhere. Stated explicitly because the
# dataset's own encoding must not be allowed to create ambiguity.
LEGITIMATE = 0
PHISHING = 1
LABEL_MEANING = {LEGITIMATE: "legitimate", PHISHING: "phishing"}


@dataclass
class AuditedRow:
    """A row that survived cleaning, with its provenance annotations."""

    url: str
    """The raw URL exactly as it appeared in the dataset."""

    normalized: str
    """BASIRAH's canonical form — the grouping key for grouped splits."""

    label: int
    registered_domain: str
    scheme: str
    hostname: str
    uses_https: bool
    source: str
    """Which dataset this row came from: 'phiusil' or 'external'."""


@dataclass
class AuditResult:
    rows: list[AuditedRow]
    manifest: DatasetManifest
    scheme_distribution: dict[str, int]
    domain_family_top: list[tuple[str, int]]
    repeated_domain_count: int
    distinct_registered_domains: int
    top_level_domains: int

    def summary(self) -> dict[str, object]:
        return {
            "dataset": self.manifest.name,
            "raw_rows_in_file": self.manifest.row_count,
            "rows_retained": len(self.rows),
            "rows_dropped": self.manifest.row_count - len(self.rows),
            "class_distribution": self.manifest.class_distribution,
            "duplicate_rows": self.manifest.duplicate_rows,
            "duplicate_urls": self.manifest.duplicate_urls,
            "conflicting_labels": self.manifest.conflicting_labels,
            "malformed_urls": self.manifest.malformed_urls,
            "null_urls": self.manifest.null_urls,
            "null_labels": self.manifest.null_labels,
            "scheme_distribution": self.scheme_distribution,
            "distinct_registered_domains": self.distinct_registered_domains,
            "top_level_domains": self.top_level_domains,
            "most_repeated_domain_families": self.domain_family_top,
            "domains_appearing_more_than_once": self.repeated_domain_count,
            "label_meaning": LABEL_MEANING,
            "sha256": self.manifest.sha256,
        }


