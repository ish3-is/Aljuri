@dataclass
class DatasetManifest:
    """Provenance record for one raw dataset file."""

    name: str
    source_url: str
    original_filename: str
    downloaded_at: str
    sha256: str
    size_bytes: int
    row_count: int = 0
    class_distribution: dict[str, int] = field(default_factory=dict)
    url_column: str = ""
    label_column: str = ""
    duplicate_rows: int = 0
    duplicate_urls: int = 0
    conflicting_labels: int = 0
    malformed_urls: int = 0
    null_urls: int = 0
    null_labels: int = 0
    license: str = "unknown"
    publication_date: str = "unknown"
    creators: str = ""
    notes: str = ""

    def write(self, directory: Path | None = None) -> Path:
        target = (directory or MANIFEST_DIR)
        target.mkdir(parents=True, exist_ok=True)
        path = target / f"{self.name}_manifest.json"
        payload = {
            "dataset_name": self.name,
            "source_url": self.source_url,
            "original_filename": self.original_filename,
            "downloaded_at": self.downloaded_at,
            "sha256": self.sha256,
            "size_bytes": self.size_bytes,
            "row_count": self.row_count,
            "class_distribution": self.class_distribution,
            "url_column": self.url_column,
            "label_column": self.label_column,
            "duplicate_rows": self.duplicate_rows,
            "duplicate_urls": self.duplicate_urls,
            "conflicting_labels": self.conflicting_labels,
            "malformed_urls": self.malformed_urls,
            "null_urls": self.null_urls,
            "null_labels": self.null_labels,
            "license": self.license,
            "publication_date": self.publication_date,
            "creators": self.creators,
            "notes": self.notes,
        }
        path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
        return path


def sha256_of(path: Path, chunk: int = 1 << 20) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(chunk), b""):
            digest.update(block)
    return digest.hexdigest()


