# AUDIT
# ====================================================================


def audit_csv(
    path: Path,
    name: str,
    source_url: str,
    source_label: str,
    license_name: str = "unknown",
    publication_date: str = "unknown",
    creators: str = "",
    label_orientation: int | None = None,
    notes: str = "",
) -> AuditResult:
    """Audit a labelled URL CSV and return cleaned rows plus a manifest.

    `label_orientation` forces the 1=phishing / 1=legitimate mapping. When
    None it is inferred from the data.
    """
    schema = inspect_columns(path)
    if schema["empty"]:
        raise ValueError(f"{path} is empty or has no header")

    header: list[str] = schema["columns"]  # type: ignore[assignment]
    url_column = find_url_column(header)
    if url_column is None:
        raise ValueError(f"No URL column found in {path}. Columns: {header}")
    label_column = find_label_column(header, url_column)
    if label_column is None:
        raise ValueError(f"No label column found in {path}. Columns: {header}")

    rows: list[AuditedRow] = []
    seen_normalized: dict[str, int] = {}
    label_conflicts: dict[str, set[int]] = {}

    duplicate_rows = 0
    duplicate_urls = 0
    conflicting_labels = 0
    malformed_urls = 0
    null_urls = 0
    null_labels = 0
    raw_row_count = 0
    class_counts: Counter[int] = Counter()
    scheme_counts: Counter[str] = Counter()
    domain_counts: Counter[str] = Counter()
    raw_labels: list[str] = []
    unregistered_labels: Counter[str] = Counter()

    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        for record in reader:
            raw_row_count += 1

            raw_url = (record.get(url_column) or "").strip()
            raw_label = (record.get(label_column) or "").strip()

            if not raw_url:
                null_urls += 1
                continue
            if not raw_label:
                null_labels += 1
                continue

            label = normalize_dataset_label(raw_label)
            if label is None:
                # Unrecognised tokens are counted, not guessed at.
                unregistered_labels[raw_label[:24]] += 1
                continue
            # len(values) guard keeps the sample small on a 235k-row file.
            if raw_row_count <= 5000:
                raw_labels.append(raw_label)

            try:
                parsed = normalize(raw_url)
            except InvalidURLError:
                malformed_urls += 1
                continue

            key = parsed.normalized.lower()

            if key in label_conflicts:
                label_conflicts[key].add(label)
            else:
                label_conflicts[key] = {label}

            if key in seen_normalized:
                duplicate_urls += 1
                duplicate_rows += 1
                continue

            seen_normalized[key] = len(rows)
            rows.append(
                AuditedRow(
                    url=raw_url,
                    normalized=parsed.normalized,
                    label=label,
                    registered_domain=parsed.registered_domain or parsed.hostname,
                    scheme=parsed.scheme,
                    hostname=parsed.hostname,
                    uses_https=parsed.uses_https,
                    source=source_label,
                )
            )
            class_counts[label] += 1
            scheme_counts[parsed.scheme] += 1
            domain_counts[parsed.registered_domain or parsed.hostname] += 1

    # Resolve the label orientation AFTER reading, then flip if needed.
    # A numeric corpus with no stated orientation is AMBIGUOUS — PhiUSIIL
    # is 1=legitimate while the convention is 1=phishing — so the run
    # fails rather than silently inverting every conclusion.
    orientation = (
        label_orientation
        if label_orientation is not None
        else detect_label_orientation(raw_labels)
    )
    if orientation == 0:
        raise LabelOrientationError(
            f"{path.name} has a numeric label column with no textual class "
            f"tokens, so the mapping of 0/1 cannot be inferred from the data. "
            f"Supply label_orientation explicitly: 1 if 1 means phishing, "
            f"-1 if 1 means legitimate. (PhiUSIIL uses -1: its documentation "
            f"states label 1 = legitimate, label 0 = phishing.)"
        )
    if orientation == -1:
        for row in rows:
            row.label = LEGITIMATE if row.label == PHISHING else PHISHING

    # Recompute the class distribution AFTER any orientation flip.
    # Counting during the read loop records pre-flip labels, which would
    # make the manifest describe a class balance the data no longer has.
    class_counts = Counter(row.label for row in rows)

    # A URL seen with BOTH labels is contradictory data. Drop it and
    # report it; picking either label would be arbitrary.
    conflicting_rows = {
        key for key, labels in label_conflicts.items() if len(labels) > 1
    }
    if conflicting_rows:
        conflicting_labels = len(conflicting_rows)
        rows = [row for row in rows if row.normalized.lower() not in conflicting_rows]
        class_counts = Counter(row.label for row in rows)

    manifest = DatasetManifest(
        name=name,
        source_url=source_url,
        original_filename=path.name,
        downloaded_at=datetime.now(timezone.utc).isoformat(),
        sha256=sha256_of(path),
        size_bytes=path.stat().st_size,
        row_count=raw_row_count,
        class_distribution={
            LABEL_MEANING[k]: v for k, v in sorted(class_counts.items())
        },
        url_column=url_column,
        label_column=label_column,
        duplicate_rows=duplicate_rows,
        duplicate_urls=duplicate_urls,
        conflicting_labels=conflicting_labels,
        malformed_urls=malformed_urls,
        null_urls=null_urls,
        null_labels=null_labels,
        license=license_name,
        publication_date=publication_date,
        creators=creators,
        notes=notes
        + (
            f" Unrecognised label tokens: {dict(unregistered_labels.most_common(5))}."
            if unregistered_labels
            else ""
        ),
    )

    return AuditResult(
        rows=rows,
        manifest=manifest,
        scheme_distribution=dict(scheme_counts.most_common()),
        domain_family_top=domain_counts.most_common(15),
        repeated_domain_count=sum(1 for count in domain_counts.values() if count > 1),
        distinct_registered_domains=len(domain_counts),
        top_level_domains=len({d.rsplit(".", 1)[-1] for d in domain_counts if "." in d}),
    )


