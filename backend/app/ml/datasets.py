def write_processed(rows: list[AuditedRow], name: str) -> Path:
    """Persist cleaned rows so experiments are reproducible without re-auditing."""
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    path = PROCESSED_DIR / f"{name}_clean.csv"
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            ["url", "normalized", "label", "registered_domain", "scheme", "source"]
        )
        for row in rows:
            writer.writerow(
                [
                    row.url,
                    row.normalized,
                    row.label,
                    row.registered_domain,
                    row.scheme,
                    row.source,
                ]
            )
    return path


def load_processed(name: str) -> list[AuditedRow]:
    """Reload previously cleaned rows."""
    path = PROCESSED_DIR / f"{name}_clean.csv"
    out: list[AuditedRow] = []
    with path.open("r", encoding="utf-8", newline="") as handle:
        for record in csv.DictReader(handle):
            out.append(
                AuditedRow(
                    url=record["url"],
                    normalized=record["normalized"],
                    label=int(record["label"]),
                    registered_domain=record["registered_domain"],
                    scheme=record["scheme"],
                    hostname="",
                    uses_https=record["scheme"] == "https",
                    source=record["source"],
                )
            )
    return out
