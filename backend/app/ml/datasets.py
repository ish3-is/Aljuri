# LABEL NORMALISATION
# ====================================================================

# PhiUSIIL ships a `label` column already as 0/1. The secondary dataset's
# encoding is unknown until inspected, so several plausible vocabularies
# are accepted and the mapping is recorded in the manifest.
_LABEL_TOKENS = {
    "1": PHISHING,
    "0": LEGITIMATE,
    "phishing": PHISHING,
    "phish": PHISHING,
    "malicious": PHISHING,
    "bad": PHISHING,
    "fraud": PHISHING,
    "1.0": PHISHING,
    "true": PHISHING,
    "legitimate": LEGITIMATE,
    "legit": LEGITIMATE,
    "benign": LEGITIMATE,
    "good": LEGITIMATE,
    "safe": LEGITIMATE,
    "normal": LEGITIMATE,
    "0.0": LEGITIMATE,
    "false": LEGITIMATE,
}


def normalize_dataset_label(raw: str) -> int | None:
    """Map a dataset's label token onto 0/1, or None if unrecognised.

    Returns None rather than guessing. A silently-defaulted label is the
    most damaging possible failure in a training pipeline: it injects
    mislabelled rows that no metric will reveal as a bug.
    """
    value = str(raw).strip().lower()
    if value in _LABEL_TOKENS:
        return _LABEL_TOKENS[value]
    # Some encodings arrive as 'Phishing'/'Legitimate' with punctuation.
    stripped = value.strip(".'\" ")
    if stripped in _LABEL_TOKENS:
        return _LABEL_TOKENS[stripped]
    return None


class UnknownLabelError(ValueError):
    """Raised by `require_label` when a token cannot be interpreted."""


class LabelOrientationError(ValueError):
    """Raised when a numeric label column's 0/1 meaning cannot be inferred.

    PhiUSIIL encodes 1=legitimate, 0=phishing — the inverse of the
    common convention. Assuming the convention silently inverts every
    downstream result, so an unstated numeric orientation is a hard
    error rather than a default.
    """


def require_label(raw: str) -> int:
    """Strict variant: raise instead of returning None.

    Used where a dataset row MUST be interpretable, so an unrecognised
    vocabulary fails the run rather than quietly dropping rows.
    """
    value = normalize_dataset_label(raw)
    if value is None:
        raise UnknownLabelError(
            f"Unrecognised dataset label {raw!r}. Expected one of: "
            f"{sorted(_LABEL_TOKENS)}"
        )
    return value


def detect_label_orientation(values: list[str]) -> int:
    """Infer whether the dataset encodes 1=phishing or 1=legitimate.

    Returns 1 when 1 means phishing, -1 when 1 means legitimate.

    WHY THIS IS NOT A MATTER OF TASTE
    ---------------------------------
    PhiUSIIL — the dataset Phase 2B trains on — uses the INVERSE of the
    near-universal convention: its own documentation states "Label 1
    corresponds to a legitimate URL, label 0 to a phishing URL". Several
    published papers invert it explicitly for the same reason.

    Getting this wrong does not produce a small error. It produces a
    model that scores google.com at 99.9% phishing and the actual
    phishing URLs at 0%. Phase 2B hit exactly that failure, which is why
    inference is now regression-tested against known-legitimate hosts.

    Inference strategy, in order of trust:
      1. textual tokens ('phishing'/'benign') — unambiguous
      2. an explicit orientation supplied by the caller
      3. numeric data — NOT inferable, so the caller must say

    A numeric corpus with no stated orientation returns 0, which the
    audit treats as a hard error rather than assuming the convention.
    """
    counts: Counter[str] = Counter()
    for value in values:
        token = str(value).strip().lower()
        if token in ("phishing", "phish", "malicious", "fraud"):
            counts["phish_token"] += 1
        elif token in ("legitimate", "legit", "benign", "good", "safe"):
            counts["legit_token"] += 1
        elif token in ("1", "1.0"):
            counts["one"] += 1
        elif token in ("0", "0.0"):
            counts["zero"] += 1

    if counts["phish_token"] and not counts["legit_token"]:
        return 1
    if counts["legit_token"] and not counts["phish_token"]:
        return -1

    # Purely numeric: genuinely ambiguous from the data alone.
    return 0


