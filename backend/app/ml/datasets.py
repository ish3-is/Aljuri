def inspect_columns(path: Path) -> dict[str, object]:
    """Report a CSV's header and a small sample, without assumptions."""
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.reader(handle)
        try:
            header = next(reader)
        except StopIteration:
            return {"columns": [], "sample_rows": [], "empty": True}

        # Take up to three sample rows, tolerating files with fewer. A
        # bare `next()` per iteration raises StopIteration on short files,
        # which previously turned a valid 2-row CSV into a crash.
        sample: list[list[str]] = []
        for row in reader:
            sample.append(row)
            if len(sample) >= 3:
                break

    return {
        "columns": header,
        "column_count": len(header),
        "sample_rows": sample,
        "empty": False,
    }


def find_url_column(header: list[str]) -> str | None:
    """Locate the URL column, tolerating naming variation."""
    lowered = {name.strip().lower(): name for name in header if name}
    for candidate in (
        "url",
        "urls",
        "uri",
        "link",
        "domain",
        "host",
        "address",
        "fullurl",
        "full_url",
    ):
        if candidate in lowered:
            return lowered[candidate]
    # Fall back to the first column whose name merely mentions url.
    for name, original in lowered.items():
        if "url" in name or "uri" in name or "link" in name:
            return original
    return None


def find_label_column(header: list[str], url_column: str | None) -> str | None:
    """Locate the label column, excluding the URL column itself."""
    lowered = {name.strip().lower(): name for name in header if name}
    for candidate in (
        "label",
        "labels",
        "class",
        "target",
        "y",
        "is_phishing",
        "isphishing",
        "type",
        "category",
        "status",
    ):
        if candidate in lowered and lowered[candidate] != url_column:
            return lowered[candidate]
    return None


