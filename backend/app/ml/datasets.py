"""
Dataset acquisition and audit for Phase 2B.

Design constraints, all deliberate:

1. RAW FILES ARE NEVER MODIFIED. Everything downstream reads them
   read-only and writes to datasets/processed/.

2. ONLY URL + LABEL ARE USED FROM PhiUSIIL. The dataset ships 54
   columns, many derived from page CONTENT (HTML tag counts, form
   counts, response-time-ish proxies). BASIRAH's live pipeline is
   URL-string-only, so training on those columns would create
   training-serving skew: the model would depend on features that do
   not exist at inference time. Only the raw URL and the label are
   ever read from the raw file; every model input is generated by
   BASIRAH's own feature extractor.

3. EVERY COUNT IS MEASURED, NEVER ASSUMED. The audit reports what is
   in the file, including the surprises.

4. CONFLICTING LABELS ARE SURFACED, NOT SILENTLY RESOLVED. If the same
   normalized URL appears with both labels, that is a dataset property
   worth reporting, and the row is dropped rather than guessed at.
"""

