# Bump when the extractor's OUTPUT changes in any way: a renamed field,
# an added field, a changed formula. Inference compares this string and
# refuses a model trained under a different version.
FEATURE_EXTRACTOR_VERSION = "2.1.0"

# ====================================================================
# FEATURES EXCLUDED FROM MODEL INPUT
# ====================================================================
# These are still COMPUTED and still displayed in the product — they are
# useful to a human reading an explanation. They are simply not fed to
# the classifier, for the reason below.
#
# `uses_https` / `uses_http` were excluded after Phase 2B measured their
# class association in two independent corpora and found it INVERTED:
#
#   PhiUSIIL   P(https | phishing) = 1.0000  P(https | legitimate) = 0.4863  lift +2.06
#   MUD 2026   P(https | phishing) = 0.8198  P(https | legitimate) = 0.9209  lift -0.89
#
# A feature whose association with the label reverses between datasets
# is not measuring phishing; it is measuring how each crawl happened to
# collect URLs. Including it produced a model whose top-ranked feature
# was `uses_https`, which then inverted on real-world data and drove
# external recall to roughly 5%.
#
# Removing it cost almost nothing in-domain (grouped AUC 0.9980 ->
# 0.9981 for XGBoost) and improved cross-dataset AUC substantially
# (0.6589 -> 0.7477). See docs/phase2b-generalization.md.
#
# The honest framing: this is not "HTTPS is useless for phishing". It
# is "in this corpus, HTTPS is a collection artefact, so a model must
# not be allowed to rely on it".
MODEL_EXCLUDED_FEATURES: frozenset[str] = frozenset({"uses_https", "uses_http"})

