"""
Feature schema: the train/serve contract.

This module is what makes the Phase 2B mandate enforceable rather than
aspirational — "training-time features and production-time features must
be generated by the same code".

The schema records the feature extractor version alongside the ordered
feature names. Training asserts the schema it was given; inference
asserts the same schema. If the extractor changes without a version bump,
or if a saved model's feature order drifts from the live extractor, the
model is REFUSED rather than silently fed misaligned input.

Nothing in this module computes features. It only describes and
validates them.
"""

from __future__ import annotations

