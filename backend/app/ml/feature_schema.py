@dataclass(frozen=True)
class FeatureSchema:
    """An ordered, versioned description of the model's input vector."""

    version: str
    feature_names: list[str]
    feature_types: list[str]

    def to_dict(self) -> dict[str, object]:
        return {
            "feature_extractor_version": self.version,
            "feature_count": len(self.feature_names),
            "features": [
                {
                    "name": name,
                    "position": index,
                    "data_type": "float64",
                    "group": FEATURE_GROUPS.get(name, "unclassified"),
                    "description": FEATURE_DESCRIPTIONS.get(name, ""),
                }
                for index, name in enumerate(self.feature_names)
            ],
        }

    def fingerprint(self) -> str:
        """Stable hash of the ordered feature list.

        Compared at load time. A change to the ORDER — not just the set —
        silently misaligns a model, so the fingerprint covers order.
        """
        payload = f"{self.version}|" + "|".join(self.feature_names)
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def current_schema() -> FeatureSchema:
    """The schema the live extractor produces, right now."""
    return FeatureSchema(
        version=FEATURE_EXTRACTOR_VERSION,
        feature_names=list(FEATURE_NAMES),
        # Every extracted feature is a float; several are 0/1 indicator
        # flags, which is why they are floats rather than booleans.
        feature_types=["float64"] * len(FEATURE_NAMES),
    )


def model_feature_names() -> list[str]:
    """The ordered subset of features the classifier actually consumes.

    This — not the full extractor output — is what a model is trained on
    and what inference must slice to. Keeping the exclusion in ONE place
    means training and serving cannot disagree about it.
    """
    return [name for name in FEATURE_NAMES if name not in MODEL_EXCLUDED_FEATURES]


def model_feature_indices() -> list[int]:
    """Column indices into the full extractor output."""
    excluded = MODEL_EXCLUDED_FEATURES
    return [i for i, name in enumerate(FEATURE_NAMES) if name not in excluded]


def save_schema(path: Path) -> Path:
    schema = current_schema()
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = schema.to_dict()
    payload["fingerprint"] = schema.fingerprint()
    # The model's actual input contract, which is a SUBSET of the
    # extractor output. Both are recorded so a reader can see exactly
    # what is computed and what is used.
    payload["model_input"] = {
        "feature_count": len(model_feature_names()),
        "features": model_feature_names(),
        "excluded_features": sorted(MODEL_EXCLUDED_FEATURES),
        "exclusion_rationale": (
            "uses_https/uses_http have an INVERTED class association "
            "between PhiUSIIL and MUD-2026 (lift +2.06 vs -0.89), so they "
            "measure crawl methodology rather than phishing. They remain "
            "visible in the product explanation but are not model inputs."
        ),
    }
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return path


class FeatureSchemaMismatch(RuntimeError):
    """Raised when a model's schema cannot be served by this extractor."""


def assert_schema_matches(
    model_features: list[str],
    model_version: str | None = None,
) -> None:
    """Refuse to use a model whose input contract does not match ours.

    This is the enforcement point for the Phase 2B rule that training and
    serving must share one feature extractor. A mismatch means the model
    was trained on a different feature set or a different ORDER, and
    feeding it the live vector would produce confident nonsense.

    Validation is against `model_feature_names()` — the subset the
    classifier actually consumes — not the full extractor output, because
    the model never sees the excluded columns.
    """
    live = model_feature_names()

    if model_version and model_version != FEATURE_EXTRACTOR_VERSION:
        raise FeatureSchemaMismatch(
            f"Model was trained with feature extractor "
            f"{model_version!r}, but this build provides "
            f"{FEATURE_EXTRACTOR_VERSION!r}. Retrain the model."
        )

    if list(model_features) == live:
        return

    missing = set(live) - set(model_features)
    extra = set(model_features) - set(live)

    # Same names, different order — the most dangerous case, because it
    # passes every set comparison and silently feeds permuted input.
    if not missing and not extra:
        raise FeatureSchemaMismatch(
            "Feature ORDER differs between the trained model and the live "
            "extractor. Refusing to predict on permuted input."
        )

    raise FeatureSchemaMismatch(
        f"Feature set differs from the trained model. "
        f"missing={sorted(missing)} unexpected={sorted(extra)}"
    )


def validate_schema_file(path: Path) -> FeatureSchema:
    """Load and verify a persisted schema against the live extractor."""
    payload = json.loads(path.read_text(encoding="utf-8"))
    schema = FeatureSchema(
        version=payload["feature_extractor_version"],
        feature_names=[f["name"] for f in payload["features"]],
        feature_types=[f["data_type"] for f in payload["features"]],
    )
    assert_schema_matches(schema.feature_names, schema.version)
    return schema
